import os
import sys
import argparse
import pandas as pd
import numpy as np

# Add the root 'Quant-Bot' directory to the Python path
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '../..')))

# Import from your dataset.py and model.py
from models.classification.dataset import build_confidence_dataset
from models.confidence.model import ConfidenceClassifier

def load_and_prepare_data(predictions_path, market_context_path, error_threshold=0.005):
    """
    Loads raw data or generates mock data if files are missing, 
    builds the dataset using dataset.py, and splits it chronologically.
    """
    print(f"Attempting to load raw data from:\n - {predictions_path}\n - {market_context_path}")
    try:
        predictions_df = pd.read_csv(predictions_path)
        market_context_df = pd.read_csv(market_context_path)
        print("Real data loaded successfully.")
    except FileNotFoundError:
        print("\n[WARNING] Real data files not found. Generating mock data to test the pipeline...")
        # Generate dummy timestamps
        timestamps = pd.date_range(start="2026-01-01", periods=1000, freq="h")
        
        # Mock Team B Predictions
        mock_predictions = np.random.normal(0, 0.02, 1000)
        predictions_df = pd.DataFrame({
            "timestamp": timestamps,
            "predicted_return": mock_predictions
        })
        
        # Force a perfect 50/50 split of 'reliable' data evenly across time
        mock_actuals = mock_predictions.copy()
        # Add a massive error to EVERY OTHER row so the validation set gets a mix of both classes
        mock_actuals[::2] += 0.05 
        
        # Mock Team A Market Context & Actual Returns
        market_context_df = pd.DataFrame({
            "timestamp": timestamps,
            "actual_return": mock_actuals,
            "feature_1_volatility": np.random.uniform(0.1, 0.5, 1000),
            "feature_2_momentum": np.random.normal(0, 1, 1000)
        })

    print("\nBuilding confidence dataset using models/classification/dataset.py...")
    # Call the function from your dataset.py
    master_df = build_confidence_dataset(
        predictions_df=predictions_df,
        market_context_df=market_context_df,
        error_threshold=error_threshold
    )

    # 1. Sort by timestamp to prevent future data leakage
    master_df = master_df.sort_values("timestamp").reset_index(drop=True)

    # 2. Drop diagnostic columns generated by dataset.py so the model doesn't cheat
    leakage_cols = ["timestamp", "actual_return", "prediction_error", "absolute_error", "prediction_magnitude", "reliable"]
    feature_cols = [col for col in master_df.columns if col not in leakage_cols]

    X = master_df[feature_cols]
    y = master_df["reliable"]

    # 3. Chronological Split: 70% Train, 15% Validation, 15% Test
    n = len(master_df)
    train_end = int(n * 0.70)
    val_end = int(n * 0.85)

    X_train, y_train = X.iloc[:train_end], y.iloc[:train_end]
    X_val, y_val = X.iloc[train_end:val_end], y.iloc[train_end:val_end]
    X_test, y_test = X.iloc[val_end:], y.iloc[val_end:]

    print(f"Data split complete. Train: {len(X_train)} | Val: {len(X_val)} | Test: {len(X_test)}")
    return X_train, y_train, X_val, y_val, X_test, y_test

def main():
    parser = argparse.ArgumentParser(description="Train the Confidence Classifier (Team C - Person B)")
    parser.add_argument('--algo', type=str, choices=['xgboost', 'random_forest'], default='xgboost')
    parser.add_argument('--predictions_path', type=str, default='data/raw/predictions.csv')
    parser.add_argument('--market_context_path', type=str, default='data/raw/market_context.csv')
    parser.add_argument('--error_threshold', type=float, default=0.005)
    parser.add_argument('--model_dir', type=str, default='saved_models/')
    
    args = parser.parse_args()

    # Phase 1: Data Preparation via dataset.py
    X_train, y_train, X_val, y_val, X_test, y_test = load_and_prepare_data(
        args.predictions_path, 
        args.market_context_path, 
        args.error_threshold
    )

    # Phase 2: Initialize and Train
    print(f"\nInitializing {args.algo.upper()} pipeline...")
    classifier = ConfidenceClassifier(algorithm=args.algo, random_state=42)
    
    print("\n--- Phase 1: Training Base Model ---")
    classifier.train(X_train, y_train)

    # Phase 3: Calibrate
    print("\n--- Phase 2: Calibrating Model ---")
    classifier.calibrate(X_val, y_val, method='isotonic')

    # Phase 4: Evaluate
    print("\n--- Phase 3: Evaluating on Test Set ---")
    metrics = classifier.evaluate(X_test, y_test)

    # Phase 5: Save Model
    print("\n--- Phase 4: Saving Model ---")
    os.makedirs(args.model_dir, exist_ok=True)
    model_filename = f"confidence_classifier_{args.algo}_v2.pkl"
    save_path = os.path.join(args.model_dir, model_filename)
    classifier.save_model(save_path)

if __name__ == "__main__":
    main()